# Load dataset
df = pd.read_csv("/content/flight_dataset_.csv")

# Convert time column to datetime
df["Scheduled_Departure_Time"] = pd.to_datetime(df["Scheduled_Departure_Time"])

# Extract hour for time interval grouping
df["Hour"] = df["Scheduled_Departure_Time"].dt.hour

# Create 3-hour time intervals
def interval(h):
    if 0 <= h < 3: return "00–03"
    elif 3 <= h < 6: return "03–06"
    elif 6 <= h < 9: return "06–09"
    elif 9 <= h < 12: return "09–12"
    elif 12 <= h < 15: return "12–15"
    elif 15 <= h < 18: return "15–18"
    elif 18 <= h < 21: return "18–21"
    else: return "21–24"

df["Time_Interval"] = df["Hour"].apply(interval)


# FIND BUSIEST & LEAST BUSY AIRPORTS
arrivals = df["Destination_Airport"].value_counts()
departures = df["Origin_Airport"].value_counts()

total_traffic = arrivals.add(departures, fill_value=0)

busiest = total_traffic.idxmax()
least_busy = total_traffic.idxmin()

print("Busiest Airport:", busiest)
print("Least Busy Airport:", least_busy)

# PASSENGER COUNT PER TIME INTERVAL
busiest_data = df[df["Origin_Airport"] == busiest].groupby("Time_Interval")["Total_Passengers"].sum()
least_busy_data = df[df["Origin_Airport"] == least_busy].groupby("Time_Interval")["Total_Passengers"].sum()

# Ensure all intervals appear on graph
interval_order = ["00–03", "03–06", "06–09", "09–12", "12–15", "15–18", "18–21", "21–24"]

busiest_data = busiest_data.reindex(interval_order, fill_value=0)
least_busy_data = least_busy_data.reindex(interval_order, fill_value=0)

# PLOT LINE GRAPH
plt.figure(figsize=(12,6))

plt.plot(interval_order, busiest_data, marker="o", linewidth=3, label=f"Busiest Airport: {busiest}")
plt.plot(interval_order, least_busy_data, marker="o", linewidth=3, label=f"Least Busy Airport: {least_busy}")

plt.title("Airport Rush Pattern Across Time Intervals", fontsize=16)
plt.xlabel("Time Interval (3-hour blocks)", fontsize=14)
plt.ylabel("Total Passengers", fontsize=14)

plt.grid(True, linestyle="--", alpha=0.5)
plt.legend(fontsize=12)
plt.tight_layout()

plt.show()

