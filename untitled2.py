def delay_category():
    conditions = [
        df["Arrival_Delay_Minutes"] < 0,
        df["Arrival_Delay_Minutes"] <= 15,
        df["Arrival_Delay_Minutes"] <= 60,
        df["Arrival_Delay_Minutes"] > 60
    ]

    choices = ["Early", "On Time", "Moderate Delay", "High Delay"]
    df["Delay Category"] = np.select(conditions, choices, default="Undefined")

    sorted_df = df.sort_values("Arrival_Delay_Minutes")

    return sorted_df[["Arrival_Delay_Minutes", "Delay Category", "Airline"]].head(10)
print("\nDelay Category Added:\n", delay_category())


def numpy_statistics():
    arr = np.array(df["Arrival_Delay_Minutes"])

    mean_delay = np.mean(arr)
    median_delay = np.median(arr)
    std_dev = np.std(arr)
    worst_index = np.argmax(arr)

    output = (
      f"Mean Delay: {mean_delay:.2f}\n"
      f"Median Delay: {median_delay:.2f}\n"
      f"Standard Deviation: {std_dev:.2f}\n"
      f"Index of Worst Delay: {worst_index}"
    )

    return output

print("\nOverall Statistics:\n", numpy_statistics())

